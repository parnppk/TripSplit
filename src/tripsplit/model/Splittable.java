package tripsplit.model;

/**
 * Abstraction: สัญญา (contract) ของ "สิ่งที่หารเงินกันได้"
 * คลาสที่ implement ต้องบอกได้ว่ายอดรวมเท่าไร และแต่ละคนต้องจ่ายเท่าไร
 */
public interface Splittable {

    // # 1. ยอดรวมของรายการ
    /** ยอดเงินรวมของรายการนี้ */
    double getTotal();

    // # 2. ส่วนที่สมาชิกแต่ละคนต้องจ่าย
    /** ส่วนที่สมาชิกคนนี้ต้องรับผิดชอบ (0 ถ้าไม่ได้ร่วมหาร) */
    double getShareFor(Member member);

    // # 3. สมาชิกคนนี้เกี่ยวข้องกับรายการนี้หรือไม่ (ใช้ตอนลบสมาชิก)
    /** สมาชิกคนนี้เกี่ยวข้องกับรายการนี้หรือไม่ (เป็นคนจ่าย หรือร่วมหาร) */
    boolean involves(Member member);
}
